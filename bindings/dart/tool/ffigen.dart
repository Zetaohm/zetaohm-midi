// Writes lib/src/bindings.g.dart: the @Native bindings of the zmidi-ffi C header (DEC-019), with every
// part of the C ABI. Run it after a change of crates/zmidi-ffi/include/zmidi.h:
// dart run tool/ffigen.dart
import 'dart:io';

import 'package:ffigen/ffigen.dart';

Future<void> main() async {
  final root = Platform.script.resolve('../');
  final header = root.resolve('../../crates/zmidi-ffi/include/zmidi.h');
  await FfiGenerator(
    input: Input(
      entryPoints: [header],
      include: (h) => h.path.endsWith('zmidi.h'),
      compilerOptions: [
        for (final part in [
          'IO',
          'UMP',
          'BLE',
          'FILE',
          'CI',
          'NET',
          'NET_AUTH',
          'USB',
        ])
          '-DZMIDI_$part',
      ],
      appendCompilerOptions: true,
    ),
    visitors: [
      Visitor(
        func: (n) => n.isIncluded = n.originalName.startsWith('zmidi_'),
        struct: (n) => n.isIncluded = n.originalName.startsWith('Zmidi'),
        // The C ABI enums are Rust `#[repr(C)]` enums: a C `int` on every target that zmidi-ffi
        // builds for, which is the size ffigen gives them.
        enumClass: (n) {
          n.isIncluded = n.originalName.startsWith('Zmidi');
          n.silenceWarning = true;
        },
        macroConstant: (n) =>
            n.isIncluded = n.originalName.startsWith('ZMIDI_'),
      ),
    ],
    output: Output(
      dart: DartOutput(path: root.resolve('lib/src/bindings.g.dart')),
      style: const NativeExternalBindings(
        assetId: 'package:zetaohm_midi/src/bindings.g.dart',
      ),
      preamble:
          '// Generated by tool/ffigen.dart from crates/zmidi-ffi/include/zmidi.h. Do not edit.\n'
          '// ignore_for_file: type=lint, unused_field, unused_element\n',
    ),
  ).generate();
}
