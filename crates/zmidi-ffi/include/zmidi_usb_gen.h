/* zmidi_usb_gen.h: the host side of a fixed USB MIDI function for C firmware (OPT-038, DEC-019).
 *
 * A host program builds the function with the run-time calls of zmidi.h (zmidi_usb_function_init,
 * zmidi_usb_function_add_setting, zmidi_usb_function_add_endpoint, zmidi_usb_function_set_blocks)
 * and calls zmidi_usb_function_print_c. It writes C source with the descriptors, the Group
 * Terminal Block sets, the endpoints and the Group Terminal masks as constant arrays. The firmware
 * includes that source and links only zmidi_usb_fixed_gtb_setup: no descriptor writer and no rule
 * check (about 1 KB of flash against 8.4 KB on Cortex-M4F).
 *
 * The source names are NAME_descriptors, NAME_gtb_sets, NAME_gtb_lens (NAME_GTB_COUNT entries),
 * NAME_endpoints (NAME_ENDPOINT_COUNT entries), NAME_group_masks_out and NAME_group_masks_in (one
 * entry for each Alternate Setting, NAME_ALTERNATE_SETTINGS entries). This header uses stdio: it
 * is for the host program only. */
#ifndef ZMIDI_USB_GEN_H
#define ZMIDI_USB_GEN_H

#ifndef ZMIDI_USB
#define ZMIDI_USB
#endif
#include "zmidi.h"

#include <stdio.h>

/* Writes `count` bytes of `data` as the body of a C array initializer. */
static void zmidi_usb_gen_bytes(FILE *out, const uint8_t *data, size_t count) {
  size_t i;
  for (i = 0; i < count; i++) {
    fprintf(out, "%s0x%02X,", i % 12 == 0 ? "\n  " : " ", data[i]);
  }
  fprintf(out, "\n");
}

/* Writes the fixed form of the function `f` as C source named `name` into `out`. It checks the
 * function as zmidi_usb_function_write does: a broken rule gives its status (REJECTED), and a
 * write error of `out` gives ZMIDI_STATUS_REJECTED too. Gives ZMIDI_STATUS_OK when all of the
 * source is written. */
static enum ZmidiStatus zmidi_usb_function_print_c(struct ZmidiUsbFunction *f, FILE *out,
                                                   const char *name) {
  /* The function is at most 0xFFFF bytes; a Group Terminal Block set is at most 5 + 13 * 16. */
  static uint8_t buf[0x10000];
  size_t len = 0, written = 0, i, sets = 0, endpoints;
  uint8_t alt;
  enum ZmidiStatus st;
  ZmidiUsbSettingEndpoint e;

  if (f == NULL || out == NULL || name == NULL) {
    return ZMIDI_STATUS_INVALID_ARGUMENT;
  }
  st = zmidi_usb_function_len(f, &len);
  if (st != ZMIDI_STATUS_OK) {
    return st;
  }
  st = zmidi_usb_function_write(f, buf, sizeof buf, &written);
  if (st != ZMIDI_STATUS_OK) {
    return st;
  }
  /* The major version only: the arrays and ZmidiUsbSettingEndpoint stay the same in every 0.x. */
  fprintf(out, "/* Generated by zmidi_usb_function_print_c (zetaohm-midi C ABI %u.x). Do not edit. */\n",
          (unsigned)ZMIDI_ABI_MAJOR);
  /* A firmware can leave arrays unused (for example the masks): no warning for them. */
  fprintf(out, "#ifndef ZMIDI_USB_FIXED_UNUSED\n#if defined(__GNUC__)\n"
               "#define ZMIDI_USB_FIXED_UNUSED __attribute__((unused))\n#else\n"
               "#define ZMIDI_USB_FIXED_UNUSED\n#endif\n#endif\n");
  fprintf(out, "static const uint8_t %s_descriptors[%lu] ZMIDI_USB_FIXED_UNUSED = {", name, (unsigned long)written);
  zmidi_usb_gen_bytes(out, buf, written);
  fprintf(out, "};\n");

  /* The Group Terminal Block set of each USB MIDI 2.0 setting, Alternate Setting 1 first. */
  for (alt = 1; alt <= ZMIDI_USB_MAX_SETTINGS; alt++) {
    st = zmidi_usb_gtb_set_write(f, alt, buf, sizeof buf, &written);
    if (st == ZMIDI_STATUS_INVALID_ARGUMENT) {
      break; /* no such setting */
    }
    if (st != ZMIDI_STATUS_OK) {
      return st;
    }
    fprintf(out, "static const uint8_t %s_gtb_set_%u[%lu] ZMIDI_USB_FIXED_UNUSED = {", name, (unsigned)alt,
            (unsigned long)written);
    zmidi_usb_gen_bytes(out, buf, written);
    fprintf(out, "};\n");
    sets++;
  }
  fprintf(out, "#define %s_GTB_COUNT %lu\n", name, (unsigned long)sets);
  /* C has no empty array: one null entry when the function has no USB MIDI 2.0 setting. */
  fprintf(out, "static const uint8_t *const %s_gtb_sets[%lu] ZMIDI_USB_FIXED_UNUSED = {", name,
          (unsigned long)(sets ? sets : 1));
  for (i = 0; i < sets; i++) {
    fprintf(out, "%s%s_gtb_set_%lu", i ? ", " : "", name, (unsigned long)(i + 1));
  }
  fprintf(out, "%s};\n", sets ? "" : "0");
  fprintf(out, "static const size_t %s_gtb_lens[%lu] ZMIDI_USB_FIXED_UNUSED = {", name, (unsigned long)(sets ? sets : 1));
  for (alt = 1; alt <= sets; alt++) {
    st = zmidi_usb_gtb_set_len(f, alt, &len);
    if (st != ZMIDI_STATUS_OK) {
      return st;
    }
    fprintf(out, "%s%lu", alt > 1 ? ", " : "", (unsigned long)len);
  }
  fprintf(out, "%s};\n", sets ? "" : "0");

  /* The endpoints for the USB stack: alternate setting, address, attributes, interval, size. */
  endpoints = zmidi_usb_function_endpoint_count(f);
  fprintf(out, "#define %s_ENDPOINT_COUNT %lu\n", name, (unsigned long)endpoints);
  fprintf(out, "static const ZmidiUsbSettingEndpoint %s_endpoints[%lu] ZMIDI_USB_FIXED_UNUSED = {\n", name,
          (unsigned long)endpoints);
  for (i = 0; i < endpoints; i++) {
    st = zmidi_usb_function_endpoint(f, i, &e);
    if (st != ZMIDI_STATUS_OK) {
      return st;
    }
    fprintf(out, "  {%u, 0x%02X, %u, %u, %u},\n", (unsigned)e.alternate_setting,
            (unsigned)e.address, (unsigned)e.transfer, (unsigned)e.interval,
            (unsigned)e.max_packet);
  }
  fprintf(out, "};\n");

  /* The Group Terminal masks of each Alternate Setting, for zmidi_usb_link_set_alternate_setting. */
  fprintf(out, "#define %s_ALTERNATE_SETTINGS %lu\n", name, (unsigned long)(sets + 1));
  fprintf(out, "static const uint16_t %s_group_masks_out[%lu] ZMIDI_USB_FIXED_UNUSED = {", name, (unsigned long)(sets + 1));
  for (alt = 0; alt <= sets; alt++) {
    fprintf(out, "%s0x%04X", alt ? ", " : "", (unsigned)zmidi_usb_function_group_mask(f, alt, 0));
  }
  fprintf(out, "};\n");
  fprintf(out, "static const uint16_t %s_group_masks_in[%lu] ZMIDI_USB_FIXED_UNUSED = {", name, (unsigned long)(sets + 1));
  for (alt = 0; alt <= sets; alt++) {
    fprintf(out, "%s0x%04X", alt ? ", " : "", (unsigned)zmidi_usb_function_group_mask(f, alt, 1));
  }
  fprintf(out, "};\n");
  return ferror(out) ? ZMIDI_STATUS_REJECTED : ZMIDI_STATUS_OK;
}

#endif /* ZMIDI_USB_GEN_H */
