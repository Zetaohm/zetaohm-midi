#!/usr/bin/env python3
"""Writes tests/c/null_args.c from include/zmidi.h (REQ-FFI-ABI-002).

For each function of the header that gives a ZmidiStatus, and for each of its pointer arguments,
the C test calls the function with that argument NULL. The other pointer arguments point to an
initialized state (for the state types of the C ABI) or to zeroed memory; the other arguments are
1, so that a length or a count does not permit the NULL. The test asserts ZMIDI_STATUS_INVALID_ARGUMENT
and that no state byte changed.

Run it after a change of the header:  python3 tests/gen_null_args.py
The test `null_args_test_is_current` of tests/c_abi.rs fails when the file is not current.
"""

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
HEADER = ROOT / "include" / "zmidi.h"
OUT = ROOT / "tests" / "c" / "null_args.c"

# Pointer arguments that may be NULL (the header says so), as "function:argument".
NULLABLE = {
    # The program may give no place for the zmidi-file error (REQ-FFI-FILE-003).
    "zmidi_clip_reader_init:error",
    "zmidi_clip_reader_next:error",
    "zmidi_clip_writer_init:error",
    "zmidi_clip_writer_config_event:error",
    "zmidi_clip_writer_start:error",
    "zmidi_clip_writer_event:error",
    "zmidi_clip_writer_finish:error",
    # "null for JSON".
    "zmidi_pe_reply:media_type",
    # "or null": a request with no ResourceList of the peer.
    "zmidi_pe_request:caps",
    "zmidi_pe_subscribe:caps",
}

# The state types: the fixture name, its guard and the code that initializes it.
FIXTURES = {
    "ZmidiBytesToUmp": ("defined(ZMIDI_IO)", "zmidi_bytes_to_ump_init(&f_ZmidiBytesToUmp, 1, 1)"),
    "ZmidiUmpToBytes": ("defined(ZMIDI_IO)", "zmidi_ump_to_bytes_init(&f_ZmidiUmpToBytes, true)"),
    "ZmidiBleReader": ("defined(ZMIDI_BLE)", "zmidi_ble_reader_init(&f_ZmidiBleReader, 1, 1)"),
    "ZmidiBleWriter": ("defined(ZMIDI_BLE)", "zmidi_ble_writer_init(&f_ZmidiBleWriter, 23)"),
    "ZmidiClipWriter": (
        "defined(ZMIDI_FILE)",
        "zmidi_clip_writer_init(&f_ZmidiClipWriter, clip_out, sizeof clip_out, &clip_config, NULL)",
    ),
    "ZmidiClipReader": ("defined(ZMIDI_FILE)", "clip_reader_fixture()"),
    "ZmidiCi": ("defined(ZMIDI_CI_DEVICE)", "ci_fixture()"),
    "ZmidiPe": ("defined(ZMIDI_CI_PROPERTY_EXCHANGE)", "zmidi_pe_init(&f_ZmidiPe, NULL, 0)"),
    "ZmidiNetHost": (
        "defined(ZMIDI_NET)",
        'zmidi_net_host_init(&f_ZmidiNetHost, (const uint8_t *)"H", (const uint8_t *)"h1")',
    ),
    "ZmidiNetClient": (
        "defined(ZMIDI_NET)",
        'zmidi_net_client_init(&f_ZmidiNetClient, (const uint8_t *)"C", (const uint8_t *)"c1")',
    ),
    "ZmidiUsbLink": ("defined(ZMIDI_USB)", "zmidi_usb_link_init(&f_ZmidiUsbLink, &usb_link_config)"),
    "ZmidiUsbFunction": (
        "defined(ZMIDI_USB)",
        "zmidi_usb_function_init_default(&f_ZmidiUsbFunction, 0, 1, false)",
    ),
}

PROLOGUE = r"""/* Generated by tests/gen_null_args.py from include/zmidi.h: do not edit.
 * REQ-FFI-ABI-002: each function that gives a ZmidiStatus gives ZMIDI_STATUS_INVALID_ARGUMENT for
 * each pointer argument that is NULL, and changes no state. The other pointers point to an
 * initialized state or to zeroed memory, and the other arguments are 1. */
#define ZMIDI_IO
#define ZMIDI_UMP
#define ZMIDI_BLE
#define ZMIDI_FILE
#define ZMIDI_CI
#define ZMIDI_NET
#define ZMIDI_NET_AUTH
#define ZMIDI_USB
#include "zmidi.h"

#include <stdint.h>
#include <stdio.h>
#include <string.h>

static int failures;
static int calls;

/* Zeroed memory for each other pointer argument (aligned for any argument type). */
static uint64_t mem[8][512];

#if defined(ZMIDI_FILE)
static uint8_t clip_out[256], clip_in[256];
static ZmidiClipConfig clip_config;
#endif
#if defined(ZMIDI_USB)
static ZmidiUsbLinkConfig usb_link_config = {false, 0xFFFF, 64, 1};
#endif
"""


def parse(header: str):
    """Gives (guard, name, [(type, name)]) for each ZmidiStatus function."""
    out = []
    guard = None
    for m in re.finditer(r"^#if ([^\n]+)$|^#endif|enum ZmidiStatus (zmidi_\w+)\(([^;]*?)\);", header, re.M | re.S):
        if m.group(0).startswith("#if "):
            guard = m.group(1).strip()
        elif m.group(0) == "#endif":
            guard = None
        else:
            args = []
            text = " ".join(m.group(3).split())
            if text and text != "void":
                for a in text.split(","):
                    a = a.strip()
                    am = re.match(r"(.*?)(\w+)$", a)
                    args.append((am.group(1).strip(), am.group(2)))
            out.append((guard, m.group(2), args))
    return out


def state_type(t: str):
    m = re.match(r"(?:const )?struct (\w+) \*$", t)
    return m.group(1) if m and m.group(1) in FIXTURES else None


def main() -> int:
    funcs = parse(HEADER.read_text())
    lines = [PROLOGUE]
    for t, (g, _) in FIXTURES.items():
        lines.append(f"#if {g}\nstatic {t} f_{t}, s_{t};\n#endif")
    lines.append(r"""
#if defined(ZMIDI_FILE)
static void clip_reader_fixture(void) {
  ZmidiClipWriter w;
  size_t len = 0;
  int ok = zmidi_clip_writer_init(&w, clip_in, sizeof clip_in, &clip_config, NULL) == ZMIDI_STATUS_OK &&
           zmidi_clip_writer_start(&w, 0, false, 0, 0, NULL) == ZMIDI_STATUS_OK &&
           zmidi_clip_writer_finish(&w, 0, &len, NULL) == ZMIDI_STATUS_OK &&
           zmidi_clip_reader_init(&f_ZmidiClipReader, clip_in, len, NULL) == ZMIDI_STATUS_OK;
  if (!ok) { fprintf(stderr, "clip reader fixture\n"); failures++; }
}
#endif

#if defined(ZMIDI_CI_DEVICE)
static void ci_fixture(void) {
  ZmidiCiConfig c;
  memset(&c, 0, sizeof c);
  c.manufacturer[1] = 0x21;
  c.max_sysex_size = 512;
  c.group_count = 1;
  c.channels_in_use = 1;
#if defined(ZMIDI_CI_PROFILES)
  c.profiles = true;
#endif
#if defined(ZMIDI_CI_PROPERTY_EXCHANGE)
  c.property_exchange = true;
#endif
#if defined(ZMIDI_CI_PROCESS_INQUIRY)
  c.process_inquiry = true;
#endif
  if (zmidi_ci_init(&f_ZmidiCi, &c, 11) != ZMIDI_STATUS_OK) { fprintf(stderr, "ci fixture\n"); failures++; }
}
#endif

/* Sets a last PE error again (a call that clears it before a NULL check is seen), then copies
 * each state, so that a call can be checked for no change. */
static void snapshot(void) {
#if defined(ZMIDI_CI_PROPERTY_EXCHANGE)
  (void)zmidi_pe_wait(&f_ZmidiPe, 1, 0, 0, 100);
#endif""")
    for t, (g, _) in FIXTURES.items():
        lines.append(f"#if {g}\n  memcpy(&s_{t}, &f_{t}, sizeof f_{t});\n#endif")
    lines.append("}\n\n/* Asserts the status and that no state changed. */\nstatic void check(enum ZmidiStatus st, const char *what) {\n  int same = 1;\n  calls++;")
    for t, (g, _) in FIXTURES.items():
        lines.append(f"#if {g}\n  same &= memcmp(&s_{t}, &f_{t}, sizeof f_{t}) == 0;\n#endif")
    lines.append(r"""  if (st != ZMIDI_STATUS_INVALID_ARGUMENT) { fprintf(stderr, "%s: status %d\n", what, (int)st); failures++; }
  if (!same) { fprintf(stderr, "%s: a state changed\n", what); failures++; }
}

int main(void) {
#if defined(ZMIDI_FILE)
  clip_config.ticks_per_quarter_note = 96;
#endif""")
    for t, (g, init) in FIXTURES.items():
        call = init if init.endswith("_fixture()") else f"if ({init} != ZMIDI_STATUS_OK) {{ fprintf(stderr, \"{t} fixture\\n\"); failures++; }}"
        if init.startswith("clip_reader") or init.startswith("ci_fixture"):
            call = f"{init};"
        lines.append(f"#if {g}\n  {call}\n#endif")
    # A last PE error, so that a call that clears it before a NULL check is seen.
    lines.append("""#if defined(ZMIDI_CI_PROPERTY_EXCHANGE)
  if (zmidi_pe_wait(&f_ZmidiPe, 1, 0, 0, 100) != ZMIDI_STATUS_REJECTED ||
      zmidi_pe_last_error(&f_ZmidiPe, NULL) == ZMIDI_PE_ERROR_NONE) {
    fprintf(stderr, "no last PE error\\n");
    failures++;
  }
#endif""")
    count = 0
    for guard, name, args in funcs:
        ptrs = [i for i, (t, _) in enumerate(args) if "*" in t]
        body = []
        for i in ptrs:
            if f"{name}:{args[i][1]}" in NULLABLE:
                continue
            vals = []
            k = 0
            for j, (t, an) in enumerate(args):
                if j == i:
                    vals.append("NULL")
                elif "*" in t:
                    st = state_type(t)
                    if st:
                        vals.append(f"&f_{st}")
                    else:
                        vals.append(f"({t})(void *)mem[{k}]")
                        k += 1
                else:
                    vals.append(f"({t})1")
            body.append(f'  snapshot();\n  check({name}({", ".join(vals)}), "{name}: {args[i][1]}");')
            count += 1
        if body:
            text = "\n".join(body)
            lines.append(f"#if {guard}\n{text}\n#endif" if guard else text)
    lines.append(r"""  printf("null_args: %d calls\n", calls);
  if (failures) fprintf(stderr, "%d failures\n", failures);
  return failures != 0;
}
""")
    text = "\n".join(lines)
    if "--check" in sys.argv:
        return 0 if OUT.exists() and OUT.read_text() == text else 1
    OUT.write_text(text)
    print(f"{OUT.relative_to(ROOT)}: {count} calls")
    return 0


if __name__ == "__main__":
    sys.exit(main())
